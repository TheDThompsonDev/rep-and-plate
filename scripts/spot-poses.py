"""Build the small Spot poses shown in the assistant cards.

The originals are 1254 px and about 1.2 MB each, far too heavy to ship inside an MCP App, and the
cards cannot fetch from the site (their CSP allows no network, and the private-preview gate would
refuse anyway). This trims each pose to its drawn area, scales it to 192 px, reduces it to a
palette PNG, and writes them as data URIs into server/agents/spot-poses.ts.

Run from the repository root:  python scripts/spot-poses.py
"""
import base64
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public" / "images" / "spot"
OUT = ROOT / "server" / "agents" / "spot-poses.ts"
SIZE = 192

# The file for each pose. Which moment uses which pose lives in src/features/spot/assistant.ts.
POSES = {
    "peek": "spot-peek.png",
    "planner": "expansion/planner.png",
    "shrug": "expansion/shrug.png",
    "dumbbell": "expansion/dumbbell.png",
    "proud": "expansion/proud.png",
    "stretch": "expansion/stretch.png",
    "detective": "expansion/detective.png",
    "chef": "expansion/chef.png",
    "coffee": "expansion/coffee.png",
}


def small(path: Path) -> bytes:
    image = Image.open(path).convert("RGBA")
    image = image.crop(image.getbbox())
    side = max(image.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    square = square.resize((SIZE, SIZE), Image.LANCZOS)
    palette = square.quantize(colors=96, method=Image.FASTOCTREE, dither=Image.NONE)
    buffer = io.BytesIO()
    palette.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def main() -> None:
    images = {}
    for name, file in POSES.items():
        data = small(SOURCE / file)
        images[name] = "data:image/png;base64," + base64.b64encode(data).decode("ascii")
        print(f"{name:10} {len(data):6} bytes")
    body = json.dumps(images, indent=2)
    OUT.write_text(
        "// Generated by scripts/spot-poses.py from public/images/spot. Do not edit by hand.\n"
        "// Small copies of Spot's poses for the assistant cards, as data URIs, so a card never fetches.\n"
        f"export const spotPoseImages: Record<string, string> = {body};\n",
        encoding="utf-8",
        newline="\n",
    )
    print("total", sum(len(value) for value in images.values()), "characters written to", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
